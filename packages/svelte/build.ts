// ── monorepo layout ─────────────────────────────────────────────────────────
// build.ts lives in packages/svelte; it compiles sources from the gpuix,
// platform and tests packages into each package's own gen/ tree.
const ROOT = resolve(import.meta.dir, '../..');
const PKG = {
	gpuix: join(ROOT, 'packages/gpuix'),
	platform: join(ROOT, 'packages/platform'),
	svelte: join(ROOT, 'packages/svelte'),
	tests: join(ROOT, 'packages/tests'),
};
const NM = join(PKG.tests, 'node_modules'); // hoisted under bun's isolated linker — tests sees svelte + streamdown
const SVELTE_PKG = join(NM, 'svelte');

const tsx = new Bun.Transpiler({ loader: 'ts' });

const SVELTE_CLIENT: Record<string, string> = {
	'svelte/store': 'svelte/src/store/index-client.js',
	'svelte/reactivity': 'svelte/src/reactivity/index-client.js',
	'svelte/legacy': 'svelte/src/legacy/legacy-client.js',
};

function svelteSubpath(spec: string): string | null {
	if (SVELTE_CLIENT[spec]) return SVELTE_CLIENT[spec];
	const sub = spec.slice('svelte/'.length);
	try {
		if (statSync(join(SVELTE_PKG, 'src', sub, 'index-client.js')).isFile())
			return `svelte/src/${sub}/index-client.js`;
	} catch {}
	return null;
}

function* walk(dir: string): Generator<string> {
	for (const f of readdirSync(dir)) {
		const p = join(dir, f);
		if (statSync(p).isDirectory()) yield* walk(p);
		else yield p;
	}
}

const relSpec = (fromDir: string, toAbs: string): string => {
	const r = relative(fromDir, toAbs).replaceAll('\\', '/');
	return r.startsWith('.') ? r : './' + r;
};

/** Specifier rewrites shared by every emitted file.
 *  - bare 'svelte' → the svelte package's client shim (package specifier —
 *    resolves from anywhere in the workspace via the root node_modules links)
 *  - 'svelte/<sub>' → the client entry file inside the installed svelte
 *    package (relative path — svelte's exports don't expose src/*)
 *  - '.svelte[.js|.ts]' import suffixes → the emitted '.js' name
 *  - '.css' imports → dropped (native stylesheet path handles styling) */
function rewriteSvelte(code: string, outAbs: string): string {
	const outDir = dirname(outAbs);
	code = code.replace(/import\s+['"][^'"]+\.css['"];?/g, '');
	code = code.replace(/(from\s+['"][^'"]+)\.svelte(?:\.[jt]s)?(['"])/g, '$1.js$2');
	code = code.replace(/from\s+(['"])(svelte(?:\/[\w/-]*)?)\1/g, (m, q, spec) => {
		if (spec === 'svelte') return `from ${q}@svelte-desktop/svelte/svelte-client.js${q}`;
		const target = svelteSubpath(spec);
		return target ? `from ${q}${relSpec(outDir, join(NM, target))}${q}` : m;
	});
	return code;
}

/** Append a sibling *.styles.js registering the compiled component's scoped
 *  CSS with the native stylesheet registry. */
async function emitStylesheet(outRoot: string, outName: string, cssCode: string, tag: string) {
	const { rules, warnings, keyframes, animations } = parseStylesheet(cssCode);
	for (const w of warnings) console.log(`[native-css] ${tag}: ${w}`);
	const stylesName = outName.replace(/\.js$/, '.styles.js');
	const sheetId = join(outRoot, outName).replaceAll('\\', '/');
	await Bun.write(
		join(outRoot, stylesName),
		`// generated by build.ts — do not edit\nimport { registerSheet } from '@svelte-desktop/gpuix/native-css/register';\n\nregisterSheet(${JSON.stringify(sheetId)}, ${JSON.stringify(rules)}, ${JSON.stringify(keyframes)}, ${JSON.stringify(animations)});\n`,
	);
	return `\nimport './${stylesName.split('/').pop()}';\n`;
}

/** Compile one first-party file (.svelte/.svelte.js/.svelte.ts) into genRoot.
 *  `file` is relative to srcRoot; output keeps the same subpath under genRoot. */
async function emitFirstParty(srcRoot: string, genRoot: string, file: string) {
	const srcAbs = join(srcRoot, file);
	const src = await Bun.file(srcAbs).text();
	try {
		const out = file.endsWith('.svelte')
			? compile(src, { generate: 'client', filename: srcAbs, dev: false, css: 'external' })
			: compileModule(file.endsWith('.ts') ? tsx.transformSync(src) : src, {
					generate: 'client',
					filename: srcAbs,
					dev: false,
				});
		let code = out.js.code;
		code = code
			// remote module lives in the svelte package's gen — same-dir for
			// kit output, package specifier for consumers elsewhere
			.replaceAll(
				'./remote.svelte.js',
				srcRoot === PKG.svelte ? './remote.js' : '@svelte-desktop/svelte/gen/remote.js',
			)
			.replaceAll(
				'./remote.svelte.ts',
				srcRoot === PKG.svelte ? './remote.js' : '@svelte-desktop/svelte/gen/remote.js',
			)
			.replaceAll('./server.ts', '../server.ts');
		const outName = file.replace(/\.svelte(\.[jt]s)?$/, '.js');
		const outAbs = join(genRoot, outName);
		// platform rune modules reach back to the uncompiled service layer —
		// the bus singleton must stay one module instance app-wide.
		if (srcRoot === join(PKG.platform, 'src')) {
			code = code.replace(
				/(from\s+['"])\.\/([\w-]+)(['"])/g,
				`$1@svelte-desktop/platform/$2.ts$3`,
			);
			// `svelte-desktop/stores` resolves to this compiled .js — the
			// adjacent .d.ts redirects type resolution to the typed source.
			if (file === 'stores.svelte.ts') {
				await Bun.write(
					join(genRoot, 'stores.d.ts'),
					"export * from '../src/stores.svelte.ts';\n",
				);
			}
		}
		code = rewriteSvelte(code, outAbs);
		mkdirSync(dirname(outAbs), { recursive: true });
		if (file.endsWith('.svelte') && out.css?.code) {
			code += await emitStylesheet(genRoot, outName, out.css.code, file);
		}
		await Bun.write(outAbs, code);
		console.log(`compiled ${relative(ROOT, srcAbs)} → ${relative(ROOT, outAbs)}`);
	} catch (e) {
		console.log(`FAILED ${file}:`, String(e).split('\n')[0]);
		throw e;
	}
}

