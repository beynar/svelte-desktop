// ── vendor: compile .svelte/.svelte.{js,ts}/.ts sources from arbitrary dirs ──
// (node_modules packages like svelte-streamdown ship .svelte sources Bun can't
// load; tests/shadcn + tests/dashboard + gpuix/src/nkit go through the same
// path). Emits into the owning package's gen/ tree.

async function vendorDir(
	srcRoot: string,
	outRoot: string,
	alias?: (spec: string) => string | null,
	opts?: { dts?: boolean },
) {
	for (const p of walk(srcRoot)) {
		const rel = relative(srcRoot, p).replaceAll('\\', '/');
		if (rel.endsWith('.d.ts')) {
			// declaration files pass through verbatim when requested — nkit's
			// style/recipe/cva types must reach gen/ alongside their .js
			if (opts?.dts) {
				const outDir = join(outRoot, dirname(rel) === '.' ? '' : dirname(rel));
				mkdirSync(outDir, { recursive: true });
				await Bun.write(join(outRoot, rel), await Bun.file(p).text());
			}
			continue;
		}
		if (rel.endsWith('.map')) continue;
		const isSvelte = rel.endsWith('.svelte');
		const isRuneMod = /\.svelte\.[jt]s$/.test(rel);
		const isTs = rel.endsWith('.ts');
		if (!isSvelte && !isRuneMod && !isTs && !rel.endsWith('.js')) continue;
		const src = await Bun.file(p).text();
		let code: string;
		let cssCode: string | null = null;
		if (isSvelte) {
			const res = compile(src, { generate: 'client', filename: p, dev: false, css: 'external' });
			code = res.js.code;
			cssCode = res.css?.code ?? null;
		} else if (isRuneMod)
			// .svelte.ts: strip types first, then compile runes
			code = compileModule(rel.endsWith('.ts') ? tsx.transformSync(src) : src, {
				generate: 'client',
				filename: p,
				dev: false,
			}).js.code;
		else if (isTs) code = tsx.transformSync(src);
		else code = src;

		const outName = rel.replace(/\.svelte(\.[jt]s)?$/, '.js').replace(/\.ts$/, '.js');
		const outAbs = join(outRoot, outName);
		const outDir = dirname(outAbs);
		// spec rewrites — aliases first (targets may still end in .svelte, the
		// generic suffix pass normalizes them), then .svelte→.js, then svelte/*
		if (alias)
			code = code.replace(/(from\s+['"])([^'"]+)(['"])/g, (m, q1, spec, q2) => {
				const t = alias(spec);
				if (!t) return m;
				// package specifiers pass through; plain targets are outRoot-relative
				return t.startsWith('@')
					? `${q1}${t}${q2}`
					: `${q1}${relative(outDir, join(outRoot, t)).replaceAll('\\', '/')}${q2}`;
			});
		code = rewriteSvelte(code, outAbs);
		mkdirSync(outDir, { recursive: true });
		if (isSvelte && cssCode) {
			code += await emitStylesheet(outRoot, outName, cssCode, rel);
		}
		await Bun.write(outAbs, code);
	}
	console.log(`vendored ${relative(ROOT, srcRoot)} → ${relative(ROOT, outRoot)}`);
}

// $lib/* → gen/shadcn targets (mirrors the registry's $lib layout onto our tree)
const shadcnAlias = (spec: string): string | null => {
	if (spec === 'bits-ui') return 'lib/bits-stub.js';
	if (spec === '$lib/utils.js') return 'lib/utils.js';
	let m = spec.match(/^\$lib\/registry\/ui\/(.+)/);
	if (m) return m[1] ?? null;
	m = spec.match(/^\$lib\/registry\/hooks\/(.+)/);
	if (m) return 'lib/hooks/' + (m[1] ?? '');
	m = spec.match(/^\$lib\/components\/icon-placeholder\/(.+)/);
	if (m) return 'lib/' + (m[1] ?? '');
	m = spec.match(/^\$lib\/(.+)/);
	if (m) return 'lib/' + (m[1] ?? '');
	return null;
};

