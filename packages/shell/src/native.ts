// The app's own native commands, one API for every language: `native.<service>.<op>(args)`,
// from pages and server code (also `host.native`). Commands come from the plugins in native/
// (Rust, Go, Swift, Objective-C, C); the build reads them back from the libraries and writes
// their types into `NativeModules` (src/native.d.ts):
//
//   import { native } from '@svelte-desktop/shell/native';
//   const { words } = await native.text.stats({ text });   // Rust: p.command("text.stats", …)
//   const message = await native.greeter.hello({ name });  // Swift: Desktop.command("greeter.hello") { (a: HelloArgs) in … }
import { callPlatform } from "./platform/bus.ts";

/** One entry per service, generated by the build (src/native.d.ts). */
// eslint-disable-next-line @typescript-eslint/no-empty-object-type
export interface NativeModules {}

const services = new Map<string, object>();

export const native: NativeModules = new Proxy({} as NativeModules, {
  get(_, service) {
    if (typeof service !== "string" || service === "then") return undefined;
    let ops = services.get(service);
    if (!ops) {
      ops = new Proxy({}, {
        get: (_, op) => (typeof op === "string" && op !== "then" ? (args: Record<string, unknown> = {}) => callPlatform(service, op, args) : undefined),
      });
      services.set(service, ops);
    }
    return ops;
  },
});
