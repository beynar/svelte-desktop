// SvelteKit adapter for the desktop shell — normally created for you by the
// Vite plugin (`desktop()` from '@kitop/shell/vite') from desktop.config.ts.
//
// Wraps @sveltejs/adapter-bun in its `compile` (embed) mode — client assets and
// prerendered pages become `with { type: 'file' }` imports that end up inside the
// executable — but intercepts the adapter's final Bun.build(): the module graph
// is written to `.desktop/stage/` with two entry points
//   desktop-main.js    UI thread: opens the window, runs the native loop
//   desktop-worker.js  Worker: SvelteKit handler behind the shell's gate
// and the packaging pipeline (src/build/package.ts) turns it into a signed .app,
// zip, DMG and release artifacts.
//
// Do not set `kit.paths.origin`: the app is served on a loopback port of its own (app-port.ts).
import fs from 'node:fs';
import { keepsTestChannel } from './build/test-channel-policy.ts';
import { metafileInputs, shippedModules } from './build/notices.ts';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveConfig } from './config.ts';

const SPECIFIERS = ['SERVER', 'MANIFEST', 'ROUTES', 'SERVER_OPTIONS'];

if (typeof Bun === 'undefined') {
	throw new Error('kitop builds with Bun: run `bunx --bun vite build` (or `bun --bun run build`)');
}
// adapter-bun is a peer dependency: resolve it from the app, not from this package
// (which may be symlinked from elsewhere).
const { default: adapter } = await import(Bun.resolveSync('@sveltejs/adapter-bun', process.cwd()));
const shell_root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * @param {import('./config.ts').ResolvedConfig | (import('./config.ts').DesktopConfig & { stage?: string, out?: string, package?: boolean })} options
 *   A resolved config (from the Vite plugin) or a plain DesktopConfig.
 */
export default function desktopAdapter(options) {
	const config = 'root' in options ? options : resolveConfig(process.cwd(), options);
	const stage = path.resolve(config.root, /** @type {any} */ (options).stage ?? '.desktop/stage');
	const out = path.resolve(config.root, /** @type {any} */ (options).out ?? '.desktop/adapter-out');
	const inner = adapter({ out, buildOptions: { compile: true } });
	return {
		...inner,
		name: 'kitop',
		async adapt(builder) {
			if (builder.config.paths?.origin) {
				builder.log.warn('kitop: kit.paths.origin is ignored; the app runs on a loopback port of its own');
			}
			const real_build = Bun.build;
			Bun.build = async (bunConfig) => {
				write_stage(bunConfig, stage);
				write_entries(stage, config, builder.getServerDirectory());
				builder.log.minor(`kitop: staged ${path.relative(process.cwd(), stage)}/desktop-{main,worker}.js`);
				return { success: true, outputs: [], logs: [] };
			};
			try {
				await inner.adapt(builder);
			} finally {
				Bun.build = real_build;
			}
			await bundle_processes(config, stage, 'jobs');
			await bundle_processes(config, stage, 'services');
			if (/** @type {any} */ (options).package === false || process.env.KITOP_SKIP_PACKAGE) return;
			const { packageApp } = await import('./build/package.ts');
			builder.log.minor('kitop: packaging');
			await packageApp(config, stage);
		}
	};
}

/**
 * Background jobs: each src/jobs/<name>.ts becomes one self-contained bundle (the
 * job + the IPC runner), compiled into the executable; the app runs a job by starting
 * its own executable with KITOP_JOB=<name> (src/jobs/host.ts) — no Bun command
 * line needed, so `build.trim` can drop it.
 * Services share this bundling mechanism, with their own IPC runner and lifetime.
 * @param {import('./config.ts').ResolvedConfig} c @param {string} stage
 * @param {'jobs' | 'services'} kind
 */
async function bundle_processes(c, stage, kind) {
	const singular = kind === 'jobs' ? 'job' : 'service';
	const runner = kind === 'jobs' ? 'runJob' : 'runService';
	const src_dir = path.join(c.root, 'src', kind);
	const out_dir = path.join(stage, kind);
	fs.rmSync(out_dir, { recursive: true, force: true });
	const names = fs.existsSync(src_dir)
		? fs.readdirSync(src_dir).filter((f) => /^[A-Za-z0-9_-]+\.(ts|js)$/.test(f)).map((f) => f.replace(/\.(ts|js)$/, ''))
		: [];
	const lines = ['// generated by @kitop/shell/adapter — background job bundles'];
	if (names.length) {
		fs.mkdirSync(path.join(out_dir, 'entries'), { recursive: true });
		for (const name of names) {
			const entry = path.join(out_dir, 'entries', `${name}.js`);
			const file = fs.existsSync(path.join(src_dir, `${name}.ts`)) ? `${name}.ts` : `${name}.js`;
			fs.writeFileSync(
				entry,
				`import entry from ${JSON.stringify(path.join(src_dir, file))};\nimport { ${runner} } from ${JSON.stringify(path.join(shell_root, 'src', kind, 'child.ts'))};\n${runner}(entry);\n`
			);
			const r = await Bun.build({ entrypoints: [entry], outdir: out_dir, target: 'bun', naming: `${name}.js`, minify: true, metafile: true });
			if (!r.success) throw new Error(`${singular} ${name}: ${r.logs.map(String).join('\n')}`);
			for (const input of metafileInputs(r.metafile, process.cwd())) shippedModules().add(input);
		}
		lines.push(`globalThis[Symbol.for('kitop.${kind}.names')] = ${JSON.stringify(names)};`);
	}
	fs.writeFileSync(path.join(stage, `desktop-${kind}.js`), lines.join('\n') + '\n');
	// The job process's entry (desktop-main.js with KITOP_JOB): constant imports, so the
	// bundles are compiled in.
	fs.writeFileSync(
		path.join(stage, `desktop-${singular}.js`),
		`// generated by @kitop/shell/adapter — runs one ${singular} in this process
const jobs = { ${names.map((n) => `${JSON.stringify(n)}: () => import('./${kind}/${n}.js')`).join(', ')} };
export async function ${runner}Process(name) {
	if (!Object.hasOwn(jobs, name)) {
		console.error(\`no ${singular} "\${name}"\`);
		process.exit(70);
	}
	await jobs[name]();
}
`
	);
	if (names.length) console.log(`kitop: ${names.length} ${singular}${names.length > 1 ? 's' : ''} (${names.join(', ')})`);
}

/** @param {string} dir @param {import('./config.ts').ResolvedConfig} c @param {string} server_dir */
function write_entries(dir, c, server_dir) {
	const src = (/** @type {string} */ f) => JSON.stringify(path.join(shell_root, 'src', f));
	// WebSockets on the app's server: src/websocket.ts, built as an entry of SvelteKit's server build
	// (vite.ts: one instance of the modules it shares with the routes, $app / $env resolved).
	const has_socket = ['ts', 'js'].some((ext) => fs.existsSync(path.join(c.root, 'src', `websocket.${ext}`)));
	const built_socket = path.join(server_dir, 'desktop-websocket.js');
	if (has_socket && !fs.existsSync(built_socket)) throw new Error('kitop: src/websocket.ts was not built with the server (is the desktop() Vite plugin in vite.config?)');
	const socket = has_socket ? built_socket : undefined;
	// The app's MCP server: src/mcp.ts, built the same way (one instance of what it shares with the
	// routes). `--mcp` runs this executable as an agent client's stdio server.
	const has_mcp = ['ts', 'js'].some((ext) => fs.existsSync(path.join(c.root, 'src', `mcp.${ext}`)));
	const built_mcp = path.join(server_dir, 'desktop-mcp.js');
	if (has_mcp && !fs.existsSync(built_mcp)) throw new Error('kitop: src/mcp.ts was not built with the server (is the desktop() Vite plugin in vite.config?)');
	const runtime = {
		appName: c.appName,
		identifier: c.identifier,
		version: c.version,
		window: c.window,
		update: c.update ? { manifestUrl: c.update.manifestUrl, publicKey: c.update.publicKey, channel: c.update.channel } : undefined,
		pagePermissions: c.bridgeAllow,
		testChannel: keepsTestChannel(c),
		protocols: c.protocols,
		singleInstance: c.singleInstance ?? true,
		network: c.network,
		command: c.command,
		quitOnLastWindowClosed: c.quitOnLastWindowClosed ?? true
	};

	fs.writeFileSync(
		path.join(dir, 'desktop-main.js'),
		`// generated by @kitop/shell/adapter
import { runShell } from ${src('main.ts')};
import { resolveLib, resolvePlugins } from ${src('resolve-lib.ts')};
import { applySystemNetwork } from ${src('system-network.ts')};
${has_mcp ? `import { runMcpBridge } from ${src('mcp/bridge.ts')};\n` : ''}const config = ${JSON.stringify(runtime, null, '\t')};
${has_mcp ? `if (process.argv[2] === '--mcp') await runMcpBridge({ identifier: config.identifier, appName: config.appName, version: config.version ?? '0.0.0' });\n` : ''}// The system's certificates and proxy for server code, before anything connects (the jobs and
// services this executable runs again inherit them).
applySystemNetwork(config.network);
// desktop.config \`command\`: host.command installs it (src/command.ts).
if (config.command) process.env.KITOP_COMMAND = config.command;
// A background job: this executable started again by the app (src/jobs/host.ts).
if (process.env.KITOP_JOB) await (await import('./desktop-job.js')).runJobProcess(process.env.KITOP_JOB);
else if (process.env.KITOP_SERVICE) await (await import('./desktop-service.js')).runServiceProcess(process.env.KITOP_SERVICE);
else
	await runShell({
		...config,
		lib: resolveLib(),
		plugins: resolvePlugins(),
		// The environment as it is now (the system network's settings, the command): a Worker
		// otherwise starts from the process's original one.
		createWorker: () => new Worker(new URL('./desktop-supervisor.js', import.meta.url).href, { env: process.env })
	});
`
	);
	fs.writeFileSync(
		path.join(dir, 'desktop-supervisor.js'),
		`// generated by @kitop/shell/adapter
import { startSupervisor } from ${src('supervisor.ts')};
startSupervisor(() => new Worker(new URL('./desktop-worker.js', import.meta.url).href, { env: process.env }));
`
	);
	fs.writeFileSync(
		path.join(dir, 'desktop-worker.js'),
		`// generated by @kitop/shell/adapter
// Order matters: the env module must evaluate before adapter-bun's handler.
import ${src('worker-env.ts')};
import { handler } from './adapter/handler.js';
import { routes } from './adapter/routes.js';
import './desktop-jobs.js';
import './desktop-services.js';
${socket ? `import websocket from ${JSON.stringify(socket)};\n` : ''}${has_mcp ? `import mcpServer from ${JSON.stringify(built_mcp)};\nimport { createMcpHandler } from '@modelcontextprotocol/server';\nimport { startMcpEndpoint } from ${src('mcp/app.ts')};\n` : ''}import { startWorker } from ${src('worker.ts')};
startWorker({ handler, routes${socket ? ', websocket' : ''}${has_mcp ? ', mcp: (identity) => startMcpEndpoint(identity, createMcpHandler, () => mcpServer)' : ''}, testChannel: ${keepsTestChannel(c)} });
`
	);
	fs.writeFileSync(path.join(dir, 'desktop.json'), JSON.stringify(runtime, null, '\t'));
	if (!fs.existsSync(path.join(dir, 'desktop-jobs.js'))) fs.writeFileSync(path.join(dir, 'desktop-jobs.js'), '// no background jobs\n');
}

/** @param {import('bun').BuildConfig} config @param {string} stage */
function write_stage(config, stage) {
	fs.rmSync(stage, { recursive: true, force: true });
	const adapter_dir = path.join(stage, 'adapter');
	fs.mkdirSync(adapter_dir, { recursive: true });

	// Resolve the adapter plugin's bare specifiers the same way the plugin does.
	/** @type {Record<string, string>} */
	const resolved = {};
	const fake_build = {
		onResolve({ filter }, cb) {
			for (const s of SPECIFIERS) {
				if (filter.test(s) && !resolved[s]) {
					const r = cb({ path: s, importer: '', resolveDir: '' });
					if (r?.path) resolved[s] = r.path;
				}
			}
		},
		onLoad() {}
	};
	for (const plugin of config.plugins ?? []) plugin.setup(fake_build);

	const files = /** @type {Record<string, string>} */ (config.files ?? {});
	const entry = /** @type {string} */ (config.entrypoints[0]);
	const src_dir = path.dirname(entry);

	// virtual file path -> staged file path
	/** @type {Map<string, string>} */
	const staged = new Map();
	const stage_name = (/** @type {string} */ abs) =>
		path.join(adapter_dir, abs.startsWith(src_dir) ? path.relative(src_dir, abs) : path.basename(abs));

	// adapter runtime sources + virtual files
	for (const name of fs.readdirSync(src_dir)) {
		const abs = path.join(src_dir, name);
		staged.set(abs, stage_name(abs));
	}
	for (const abs of Object.keys(files)) staged.set(abs, stage_name(abs));

	/** @type {Record<string, string>} specifier -> replacement relative to adapter_dir */
	const spec_map = {};
	for (const [spec, abs] of Object.entries(resolved)) {
		const target = staged.get(abs) ?? abs; // SERVER points at .svelte-kit/bun-tmp/server.js on disk
		let rel = path.relative(adapter_dir, target).replaceAll(path.sep, '/'); // an import, on Windows too
		if (!rel.startsWith('.')) rel = `./${rel}`;
		spec_map[spec] = rel;
	}

	for (const [abs, dest] of staged) {
		let source = files[abs] ?? (fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null);
		if (source == null) continue;
		source = source.replace(
			/(from\s*|import\s*\(?\s*)(['"])(SERVER|MANIFEST|ROUTES|SERVER_OPTIONS)\2/g,
			(_, pre, q, spec) => `${pre}${q}${spec_map[spec]}${q}`
		);
		fs.writeFileSync(dest, source);
	}

	const entry_rel = path.relative(stage, staged.get(entry)).replaceAll(path.sep, '/');
	fs.writeFileSync(path.join(stage, 'entry.js'), `import './${entry_rel}';\n`);

	const { plugins, files: _f, ...rest } = config;
	fs.writeFileSync(
		path.join(stage, 'adapter-build-config.json'),
		JSON.stringify({ ...rest, plugins: plugins?.map((p) => p.name), resolved, spec_map }, null, 2)
	);
}
