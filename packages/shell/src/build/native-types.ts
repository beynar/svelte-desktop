// The types of `native` (src/native.ts): every plugin library (libapp-native from Swift / ObjC / C,
// the Rust and Go ones) is read back in a subprocess — a Go runtime can't be loaded twice in one
// process — and its commands become `NativeModules` entries in src/native.d.ts (keep it in git).
// Typed commands come from `sd_plugin_describe` (the Rust, Go and Swift SDKs export it); a library
// without it (Objective-C SDCommand, raw C) is run against a host that records `register_op`, so its
// commands are still listed, typed `unknown`.
import { $ } from "bun";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export interface PluginDescription {
  language: string;
  /** `args` null: no arguments; `typed` false: raw arguments, unknown result. */
  commands: Array<{ service: string; op: string; args: string | null; result: string; typed?: boolean }>;
}

const DESCRIBE = `const { dlopen, FFIType, CString, JSCallback, ptr } = require("bun:ffi");
const path = process.argv[1];
let out = null;
try {
  const lib = dlopen(path, { sd_plugin_describe: { args: [], returns: FFIType.ptr } });
  out = JSON.parse(new CString(lib.symbols.sd_plugin_describe()).toString());
} catch {}
if (!out) {
  const commands = [];
  const fn = (f, args, returns) => new JSCallback(f, { args, returns }).ptr;
  const P = FFIType.ptr;
  const host = new BigUint64Array(9); // sd_host: int abi (padded) + 8 function pointers
  host[0] = 1n;
  host[1] = BigInt(fn((s, o) => (commands.push({ service: new CString(s).toString(), op: new CString(o).toString(), args: null, result: "unknown", typed: false }), 0), [P, P, P, P], FFIType.i32));
  for (const i of [2, 3, 4, 8]) host[i] = BigInt(fn(() => {}, [P, P, P], FFIType.void));
  for (const i of [5, 6]) host[i] = BigInt(fn(() => null, [FFIType.i32], P));
  host[7] = BigInt(fn(() => -1, [P], FFIType.i32));
  const lib = dlopen(path, { sd_plugin_init: { args: [P], returns: FFIType.i32 } });
  lib.symbols.sd_plugin_init(ptr(host));
  out = { language: "c", commands };
}
process.stdout.write(JSON.stringify(out));`;

/** Each library's commands. A library that can't be read (another architecture, a crash) is skipped. */
export async function describePlugins(libs: string[]): Promise<PluginDescription[]> {
  const out: PluginDescription[] = [];
  for (const lib of libs) {
    const r = await $`${process.execPath} -e ${DESCRIBE} ${lib}`.nothrow().quiet();
    if (r.exitCode === 0 && r.stdout.length) out.push(JSON.parse(r.stdout.toString()));
  }
  return out;
}

/** src/native.d.ts: the commands as `NativeModules` entries (written only when it changes). */
export function writeNativeTypes(root: string, descriptions: PluginDescription[]): string {
  const services = new Map<string, string[]>();
  for (const d of descriptions)
    for (const c of d.commands) {
      const sig =
        c.typed === false
          ? `${c.op}(args?: Record<string, unknown>): Promise<unknown>;`
          : c.args === null
            ? `${c.op}(): Promise<${c.result}>;`
            : `${c.op}(args: ${c.args}): Promise<${c.result}>;`;
      services.set(c.service, [...(services.get(c.service) ?? []), `\t\t\t${sig}`]);
    }
  const body = [...services].map(([s, ops]) => `\t\t${JSON.stringify(s)}: {\n${ops.join("\n")}\n\t\t};`).join("\n");
  const from = [...new Set(descriptions.map((d) => d.language))].join(", ") || "none";
  const text = `// Generated by svelte-desktop from the plugins in native/ (${from}): the types of \`native\`. Don't edit.\nexport {};\n\ndeclare module '@svelte-desktop/shell/native' {\n\tinterface NativeModules {\n${body}\n\t}\n}\n`;
  const file = join(root, "src", "native.d.ts");
  mkdirSync(join(root, "src"), { recursive: true });
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text);
  return file;
}

/** Describe the plugin libraries and write their types; returns the number of commands. */
export async function typeNativePlugins(root: string, libs: string[]): Promise<number> {
  if (!libs.length) return 0;
  const descriptions = await describePlugins(libs);
  writeNativeTypes(root, descriptions);
  return descriptions.reduce((n, d) => n + d.commands.length, 0);
}
