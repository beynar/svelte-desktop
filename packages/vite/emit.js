/**
 * Native entry emission — shared by adapter.js, build.js and dev.js.
 *
 * Writes `<outDir>/app.js`: a backend-neutral boot module shaped exactly
 * like packages/tests/main-kit.ts + kit-app.ts — installGlobals, GpuixRenderer
 * → setRenderer/init/setViewport, materialize a gdom target, createRouter
 * over the virtual manifest, mount Shell, router.start, then the tick loop.
 *
 * `buildNativeApp()` then runs vite build on that entry with the plugin —
 * an SSR-targeted build so bare deps (@gpuix/native, node:*) externalize
 * and only our compiled sources bundle. `svelte` is force-bundled through
 * the client-entry alias — an externalized bare 'svelte' would resolve to
 * the *server* entry under Bun.
 */
import { existsSync, mkdirSync } from 'node:fs';
import { writeFileSync } from 'node:fs';
import { join, resolve as resolvePath, isAbsolute } from 'node:path';
import { GDOM, NATIVE, KIT_RUNTIME, KIT_SHELL, GPUIX_NATIVE_EXTERNAL, toImportSpecifier } from './paths.js';
import { svelteNative } from './vite-plugin.js';

