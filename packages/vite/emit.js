/**
 * Emit the native entry module. Returns the absolute entry path.
 * opts: { root, outDir, backend, title, width, height, startPath, hooks }
 */
export function emitEntry({
	root,
	outDir = '.svelte-native',
	backend = '@gpuix/native',
	rendererClass = 'GpuixRenderer',
	title = 'svelte-native app',
	width = 1180,
	height = 780,
	startPath = '/',
	hooks = 'src/hooks.ts',
	headless = false,
	// The app owns the full window surface — a hidden titlebar lets it draw
	// under the traffic lights, and app-owned drag means `data-window-drag`
	// regions (not AppKit) move the window, so strip clicks land instantly.
	titlebarTransparent = true,
	appOwnsTitlebarDrag = true,
	trafficLightX,
	trafficLightY,
}) {
	const outDirAbs = isAbsolute(outDir) ? outDir : join(root, outDir);
	mkdirSync(outDirAbs, { recursive: true });

	const spec = (abs) => toImportSpecifier(abs, root);
	// hooks are optional — a static import of a missing file would break the
	// build, so the entry shape depends on what exists on disk
	const hooksFile = ['ts', 'js']
		.map((ext) => join(root, hooks.replace(/\.(ts|js)$/, '') + '.' + ext))
		.find((f) => existsSync(f));

	// headless: TestGpuixRenderer — no window; pump events, print painted
	// text, exit. A CI-shaped smoke path for the same compiled bundle.
	const boot = headless
		? `const renderer = new ${rendererClass}(${width}, ${height});
setRenderer(renderer);
initPlatform(renderer);
setViewport(${width}, ${height});

const target = doc.createElement('div');
target.setAttribute('style', 'display:flex;flex-direction:column;width:${width}px;height:${height}px');
doc.body.appendChild(target);
materializeRoot(target);

const router = createRouter({ routes, endpoints, matchers, hooks });
mount(Shell, { target, props: { router } });
flush();
await router.start(${JSON.stringify(startPath)});

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
for (let i = 0; i < 8; i++) {
	for (const ev of renderer.drainEvents()) dispatchPayload(ev);
	await sleep(10);
	flush();
	renderer.flush();
	drainAfterRender();
}
renderer.flush();
console.log('[svelte-native painted]', renderer.getPaintedText().join(' | '));
process.exit(0);`
		: `// reload-safe host — process, window, GPU + napi binding persist on
// globalThis while vite's runner clears + re-runs this module graph on
// full-reload. teardown() drops the previous tree before we remount.
const host = (globalThis.__svelteNativeHost ??= {});

// Synchronously claim this generation BEFORE the first await — a second
// evaluation landing mid-remount must see a stale gen and bail, and native
// events dispatched during the async gap must not reach a dying realm.
const gen = (host.gen = (host.gen ?? 0) + 1);
host.dispatch = null;           // silence native events until we're ready
host.teardown?.();              // tear down the previous tree (if any)
host.teardown = () => {          // provisional teardown — detach only
	try { for (const c of [...doc.body.childNodes]) doc.body.removeChild(c); } catch {}
	try { flush(); } catch {}
};

// persist the id allocator across reloads — a fresh realm starting at 1
// would collide with the old realm's live native ids
if (host.nextId !== undefined) { const { __setNextId } = ${JSON.stringify(spec(NATIVE))}; __setNextId?.(host.nextId); }

if (!host.renderer) {
	host.renderer = new ${rendererClass}((err, payload) => {
		if (err) {
			console.error('[gpuix]', err);
			return;
		}
		// dispatch through the CURRENT realm — the renderer + this callback
		// outlive module reloads, gdom's listener registry doesn't
		host.dispatch?.(payload);
	});
	host.renderer.init({
		title: ${JSON.stringify(title)},
		width: ${width},
		height: ${height},
		titlebarTransparent: ${titlebarTransparent},
		appOwnsTitlebarDrag: ${appOwnsTitlebarDrag},${trafficLightX !== undefined ? `\n\t\ttrafficLightX: ${trafficLightX},` : ''}${trafficLightY !== undefined ? `\n\t\ttrafficLightY: ${trafficLightY},` : ''}
	});
}
host.dispatch = dispatchPayload;
setRenderer(host.renderer);
// bind the platform bus every generation — the module graph re-executes
// on reload while host.renderer persists; initPlatform re-binds cleanly.
initPlatform(host.renderer);
setViewport(${width}, ${height});

const target = doc.createElement('div');
// 100%×100% — the Rust renderer wraps the root in a size_full div; the
// target must claim that space or it stays content-sized in the top-left.
target.setAttribute('style', 'display:flex;flex-direction:column;width:100%;height:100%');
doc.body.appendChild(target);
materializeRoot(target);

const router = createRouter({ routes, endpoints, matchers, hooks });
const handle = mount(Shell, { target, props: { router } });
flush();

// resume where the previous mount left off — history[historyIndex] is the
// visible entry, not the newest (history.at(-1) returns the wrong route
// after back())
let lastPath = null;
try {
	const ix = host.router?.historyIndex ?? -1;
	const href = ix >= 0 ? host.router?.history?.[ix]?.url : host.router?.history?.at(-1)?.url;
	if (href) { const u = new URL(href); lastPath = u.pathname + u.search + u.hash; }
} catch {}
await router.start(lastPath ?? ${JSON.stringify(startPath)});
if (gen !== host.gen) { // superseded during async route start — bail
	try { unmount(handle)?.catch?.(() => {}); } catch {}
} else {
	host.router = router;
	host.teardown = () => {
		// unmount returns a promise under experimental.async — its rejection
		// (async-boundary teardown) must not surface as an unhandled rejection
		try { unmount(handle)?.catch?.(() => {}); } catch {}
		try { for (const c of [...doc.body.childNodes]) doc.body.removeChild(c); } catch {}
		try { flush(); } catch {}
	};
}

// Per-iteration frame budget: tick() services the native runloop for up to
// this long — AX writes and other mach-port sources dispatch on arrival
// instead of waiting for the next poll, which is what keeps window-manager
// resizes responsive — and the setTimeout paces the loop to the same period.
// On macOS the budget must stay well under a vsync period: the display link
// feeds a coalescing dispatch source, so a pump slower than the display's
// refresh drops ticks — a 16ms budget caps drawing at ~57Hz on a 95Hz/120Hz
// panel and batches scroll deltas into steppy frames. 4ms keeps every vsync
// serviced on up to ~240Hz displays. On other platforms tick() doesn't pump
// a native runloop, so the 16ms pacing is just the JS work-loop cadence.
const FRAME_MS = process.platform === 'darwin' ? 4 : 16;
const loop = () => {
	if (gen !== host.gen) return; // superseded by a newer evaluation
	const started = performance.now();
	const running = host.renderer.tick(FRAME_MS);
	flush();
	drainAfterRender();
	if (running === false) process.exit(0);
	setTimeout(loop, Math.max(1, FRAME_MS - (performance.now() - started)));
};
loop();`;

	const code = `// generated by svelte-desktop-native — native app entry (main-kit.ts + kit-app.ts shape)
import { ${rendererClass} } from ${JSON.stringify(backend)};
import { installGlobals, doc, materializeRoot, setViewport, dispatchPayload } from ${JSON.stringify(spec(GDOM))};
import { setRenderer, flush, drainAfterRender } from ${JSON.stringify(spec(NATIVE))};
import { initPlatform } from '@svelte-desktop/platform';
import { createRouter } from ${JSON.stringify(spec(KIT_RUNTIME))};
import { routes, endpoints, matchers } from 'virtual:svelte-native/manifest';
${hooksFile ? `import * as hooks from ${JSON.stringify(spec(hooksFile))};` : 'const hooks = {};'}
import Shell from ${JSON.stringify(spec(KIT_SHELL))};
import { mount, unmount } from 'svelte';

installGlobals();

${boot}
`;
	const entryPath = join(outDirAbs, 'app.js');
	writeFileSync(entryPath, code);
	writeFileSync(join(outDirAbs, 'ambient.d.ts'), AMBIENT_DTS);
	return { entryPath, outDirAbs, hasHooks: !!hooksFile };
}

/**
 * Emit + build: produces the spawnable bundle at <outDir>/app.js.
 * Uses the consumer's vite.config when present (it should own the plugin —
 * see README); adds svelteNative() inline only as a fallback for projects
 * without a config file.
 */
export async function buildNativeApp({
	root = process.cwd(),
	outDir = '.svelte-native',
	pluginOptions = {},
	vite: viteOverrides = {},
	dev = false,
	...entryOpts
} = {}) {
	root = resolvePath(root);
	const { entryPath, outDirAbs } = emitEntry({ root, outDir, ...entryOpts });
	const { build } = await import('vite');
	const hasConfig =
		existsSync(join(root, 'vite.config.js')) ||
		existsSync(join(root, 'vite.config.ts')) ||
		existsSync(join(root, 'vite.config.mjs'));
	// SVELTE_NATIVE_DEV: the plugin's `config` hook reads this so a build
	// spawned from a dev session compiles Svelte in dev mode (a consumer's
	// own svelteNative() instance picks it up the same way — pluginOptions
	// only reach the fallback inline plugin).
	const prevDev = process.env.SVELTE_NATIVE_DEV;
	if (dev) process.env.SVELTE_NATIVE_DEV = '1';
	// the entry was just emitted with our opts (headless/rendererClass) —
	// keep a consumer/fallback svelteNative() config hook from re-emitting
	// app.js with its own defaults mid-build
	const prevWritten = process.env.SVELTE_NATIVE_ENTRY_WRITTEN;
	process.env.SVELTE_NATIVE_ENTRY_WRITTEN = '1';
	try {
		await build({
			root,
			configFile: hasConfig ? undefined : false,
			plugins: hasConfig ? [] : [svelteNative({ root, ...pluginOptions })],
			logLevel: 'info',
			...viteOverrides,
			build: {
				ssr: entryPath,
				outDir: outDirAbs,
				emptyOutDir: false, // the emitted entry lives in the same dir
				minify: false,
				target: 'esnext',
				rollupOptions: {
					// bun:sqlite et al — not node builtins; external for the spawned bun
					external: [/^bun:/, GPUIX_NATIVE_EXTERNAL],
					output: { format: 'esm', entryFileNames: 'app.js' },
				},
				...(viteOverrides.build ?? {}),
			},
			ssr: {
				// bundle the client entry + its small runtime dep closure; keep
				// real deps (@gpuix/native, node:*) external for the spawned bun
				noExternal: ['svelte', 'esm-env', 'clsx', 'devalue'],
				...(viteOverrides.ssr ?? {}),
			},
		});
	} finally {
		if (prevDev === undefined) delete process.env.SVELTE_NATIVE_DEV;
		else process.env.SVELTE_NATIVE_DEV = prevDev;
		if (prevWritten === undefined) delete process.env.SVELTE_NATIVE_ENTRY_WRITTEN;
		else process.env.SVELTE_NATIVE_ENTRY_WRITTEN = prevWritten;
	}
	return { bundlePath: join(outDirAbs, 'app.js'), outDirAbs };
}
