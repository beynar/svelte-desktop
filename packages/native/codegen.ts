/**
 * codegen.ts — reads commands.json, emits bindings.ts (typed $native surface).
 * `bun packages/native/codegen.ts` — run from repo root.
 */
import { readFileSync, writeFileSync } from 'fs';

interface Cmd {
	name: string; symbol: string; kind: 'scalar' | 'bytes-in' | 'json-in-json-out';
	args: { name: string; type: string }[];
	returns: string; errors: Record<string, string>; freeSymbol?: string;
}
const reg = JSON.parse(readFileSync('packages/native/commands.json', 'utf8'));

const ffiType = (t: string) =>
	({ i64: 'FFIType.i64', utf8: "FFIType.ptr, FFIType.usize" })[t] ?? 'FFIType.ptr';

let ffiDecl = '';
let body = '';
const needsFree = reg.commands.some((c: Cmd) => c.freeSymbol);

for (const c of reg.commands as Cmd[]) {
	const ffiArgs = c.args.flatMap((a) =>
		a.type === 'utf8' ? ['FFIType.ptr', 'FFIType.usize'] : [ffiType(a.type)]);
	if (c.kind === 'json-in-json-out') ffiArgs.push('FFIType.ptr'); // out_len
	ffiDecl += `\t${c.symbol}: { args: [${ffiArgs.join(', ')}], returns: ${c.returns === 'json' ? 'FFIType.ptr' : ffiType(c.returns)} },\n`;
	if (c.freeSymbol) ffiDecl += `\t${c.freeSymbol}: { args: [FFIType.ptr, FFIType.usize], returns: FFIType.void },\n`;

	const tsArgs = c.args.map((a) => `${a.name}: ${a.type === 'i64' ? 'number | bigint' : 'string | Uint8Array'}`).join(', ');
	if (c.kind === 'scalar') {
		body += `export function ${c.name}(${tsArgs}): bigint {\n\treturn lib.symbols.${c.symbol}(${c.args.map((a) => a.name).join(', ')});\n}\n\n`;
	} else if (c.kind === 'bytes-in') {
		body += `export function ${c.name}(${tsArgs}): bigint {\n\tconst buf = typeof ${c.args[0].name} === 'string' ? enc.encode(${c.args[0].name}) : ${c.args[0].name};\n\tconst r = lib.symbols.${c.symbol}(buf, buf.byteLength);\n\tif (r < 0n) throw new NativeError(${JSON.stringify(c.errors)}[String(r)] ?? 'unknown');\n\treturn r;\n}\n\n`;
	} else {
		body += `export function ${c.name}(${tsArgs}): unknown {\n\tconst buf = typeof ${c.args[0].name} === 'string' ? enc.encode(${c.args[0].name}) : ${c.args[0].name};\n\tconst outLen = new BigUint64Array(1);\n\tconst p = lib.symbols.${c.symbol}(buf, buf.byteLength, ptr(outLen));\n\tif (!p) throw new NativeError('transform_failed_or_panic');\n\tconst out = dec.decode(new Uint8Array(toArrayBuffer(p, 0, Number(outLen[0]))).slice());\n\tlib.symbols.${c.freeSymbol!}(p, Number(outLen[0]));\n\treturn JSON.parse(out);\n}\n\n`;
	}
}

const out = `// GENERATED by packages/native/codegen.ts from commands.json — do not edit.
import { dlopen, FFIType, ptr, toArrayBuffer } from 'bun:ffi';
import { join } from 'path';

export class NativeError extends Error { constructor(public code: string) { super(code); } }

const lib = dlopen(
	join(import.meta.dir, '../../crates/native-core/lib${reg.library}.dylib'),
	{
${ffiDecl.slice(0, -1)}
	},
);
const enc = new TextEncoder();
const dec = new TextDecoder();

${body}`;

writeFileSync('packages/native/bindings.ts', out);
console.log('emitted packages/native/bindings.ts');
