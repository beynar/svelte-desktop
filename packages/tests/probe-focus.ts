import { TestGpuixRenderer } from '@gpuix/native';
import { installGlobals, doc, materializeRoot } from '@svelte-desktop/gpuix/gdom';
import { setRenderer, flush } from '@svelte-desktop/gpuix/native';
installGlobals();
const renderer = new TestGpuixRenderer(640, 600);
setRenderer(renderer as any);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const pump = async () => { flush(); renderer.flush(); await sleep(30); };
const root = doc.createElement('div');
doc.body.appendChild(root);
materializeRoot(root);
const d = doc.createElement('div');
d.setAttribute('tabindex', '0');
d.setAttribute('style', 'width:50px;height:50px');
d.addEventListener('focus', () => {});
d.addEventListener('blur', () => {});
root.appendChild(d);
const xb = doc.createElement('x-button' as any);
xb.addEventListener('focus', () => {});
xb.addEventListener('blur', () => {});
root.appendChild(xb);
await pump();
console.log('div nativeId', d.nativeId, 'xbutton nativeId', xb.nativeId);
renderer.focusElement(d.nativeId);
await pump();
console.log('after focus div:', JSON.stringify(renderer.drainEvents()));
renderer.focusElement(xb.nativeId);
await pump();
console.log('after focus xbutton:', JSON.stringify(renderer.drainEvents()));
