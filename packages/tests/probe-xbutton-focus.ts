import { TestGpuixRenderer } from '@gpuix/native';
import { installGlobals, doc, materializeRoot } from '@svelte-desktop/gpuix/gdom';
import { setRenderer, flush } from '@svelte-desktop/gpuix/native';
installGlobals();
const renderer = new TestGpuixRenderer(640, 600);
setRenderer(renderer as any);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const pump = async () => { flush(); renderer.flush(); await sleep(30); };
const root = doc.createElement('div');
doc.body.appendChild(root);
materializeRoot(root);
const b1 = doc.createElement('x-button' as any);
b1.setAttribute('style', 'width:100px;height:50px');
b1.addEventListener('focus', () => {});
b1.addEventListener('blur', () => {});
root.appendChild(b1);
const b2 = doc.createElement('x-button' as any);
b2.setAttribute('style', 'width:100px;height:50px;margin-top:80px');
b2.addEventListener('focus', () => {});
b2.addEventListener('blur', () => {});
root.appendChild(b2);
await pump();
const bb1 = (renderer as any).getElementBounds((b1 as any).nativeId);
const bb2 = (renderer as any).getElementBounds((b2 as any).nativeId);
renderer.drainEvents();
renderer.simulateClick(bb1.x + bb1.width / 2, bb1.y + bb1.height / 2);
await pump();
console.log('click b1 ->', JSON.stringify(renderer.drainEvents()));
renderer.simulateClick(bb2.x + bb2.width / 2, bb2.y + bb2.height / 2);
await pump();
console.log('click b2 ->', JSON.stringify(renderer.drainEvents()));
