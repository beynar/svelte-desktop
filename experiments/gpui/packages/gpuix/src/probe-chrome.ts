import { TestGpuixRenderer } from '@gpuix/native';
import { installGlobals, doc, materializeRoot, setViewport } from './gdom';
import { setRenderer, flush, drainAfterRender } from './native';
installGlobals();
const { default: themeCss } = await import('./gen/theme-css.js');
const renderer = new TestGpuixRenderer(1180, 800);
setRenderer(renderer as any); setViewport(1180, 780);
const st = doc.createElement('style');
st.textContent = themeCss;
doc.head.appendChild(st);
doc.documentElement.classList.add('dark');
const { mount } = await import('../node_modules/svelte/src/index-client.js');
const { default: Dashboard } = await import('./gen/dashboard/Dashboard.js');
const target = doc.createElement('div');
target.setAttribute('style', 'display:flex;flex-direction:column;width:1180px;height:780px');
doc.body.appendChild(target);
materializeRoot(target as any);
mount(Dashboard, { target: target as any });
await new Promise(r => setTimeout(r, 80));
flush(); renderer.flush(); drainAfterRender();
const all: any[] = [];
const walk = (n: any) => { if (n.nodeType === 1) all.push(n); (n.childNodes ?? []).forEach(walk); };
walk(doc.documentElement);
const pick = (pred: (e: any) => boolean, n = 2) => all.filter(pred).slice(0, n);
const show = (el: any, label: string) => {
	console.log(`\n${label} <${el.tagName}> cls="${el._className?.slice(0, 80)}"`);
	console.log('  merged:', JSON.stringify(Object.fromEntries(el.mergedStyleProps())).slice(0, 500));
};
for (const e of pick(e => e._className?.includes('stat-card'), 1)) show(e, 'CARD');
for (const e of pick(e => e._className?.includes('cn-card-content'), 1)) show(e, 'CARD-CONTENT');
for (const e of pick(e => e._className?.includes('cn-badge'), 2)) show(e, 'BADGE');
for (const e of pick(e => e.tagName === 'BUTTON' && e._className?.includes('menu'), 3)) show(e, 'MENUBTN');
for (const e of pick(e => e._className?.includes('topbar'), 1)) show(e, 'TOPBAR');
for (const e of pick(e => e._className?.includes('cn-sidebar'), 4)) show(e, 'SIDEBAR');
